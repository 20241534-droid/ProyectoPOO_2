    private void btRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btRegistrarActionPerformed
        // TODO add your handling code here
        
        String codigo = txtCodigo.getText();
        String marca = txtMarca.getText();
        String modeloV = txtModelo3.getText();
        String color = txtColor.getText();
        int anio = Integer.parseInt(txtAnioF.getText());
        String tipo = bxTipo.getSelectedItem().toString();
        double precio = Double.parseDouble(txtPrecioB.getText());
        String estado = bxEstado.getSelectedItem().toString();

        modelo.addRow(new Object[]{codigo, marca, modeloV, color, anio, tipo, precio, estado});
        limpiarCampos();
    
    }//GEN-LAST:event_btRegistrarActionPerformed

    private void btEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btEliminarActionPerformed
        // TODO add your handling code here:
        
        int fila = jTable1.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(null, "Seleccione un vehículo de la tabla.");
            return;
        }
        modelo.removeRow(fila);
    
    }//GEN-LAST:event_btEliminarActionPerformed

    private void limpiarCampos() {
        txtCodigo.setText("");
        txtMarca.setText("");
        txtModelo3.setText("");
        txtColor.setText("");
        txtAnioF.setText("");
        txtPrecioB.setText("");
        bxTipo.setSelectedIndex(0);
        bxEstado.setSelectedIndex(0);
    }

    
    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {                                     
        int fila = jTable1.getSelectedRow();
        txtCodigo.setText(modelo.getValueAt(fila, 0).toString());
        txtMarca.setText(modelo.getValueAt(fila, 1).toString());
        txtModelo3.setText(modelo.getValueAt(fila, 2).toString());
        txtColor.setText(modelo.getValueAt(fila, 3).toString());
        txtAnioF.setText(modelo.getValueAt(fila, 4).toString());
        bxTipo.setSelectedItem(modelo.getValueAt(fila, 5).toString());
        txtPrecioB.setText(modelo.getValueAt(fila, 6).toString());
        bxEstado.setSelectedItem(modelo.getValueAt(fila, 7).toString());
    }
