    // Devuelve un array de String con todos los vehículos (Marca + Modelo)
    public String[] getVehiculos() {
        int filas = modelo.getRowCount();
        String[] vehiculos = new String[filas];
        for(int i = 0; i < filas; i++) {
            vehiculos[i] = modelo.getValueAt(i, 1) + " " + modelo.getValueAt(i, 2);
        }
        return vehiculos;
    }

    // Devuelve el precio de un vehículo según Marca + Modelo
    public double getPrecio(String vehiculoNombre) {
        int filas = modelo.getRowCount();
        for(int i = 0; i < filas; i++) {
            String nombre = modelo.getValueAt(i, 1) + " " + modelo.getValueAt(i, 2);
            if(nombre.equals(vehiculoNombre)) {
                return Double.parseDouble(modelo.getValueAt(i, 6).toString());
            }
        }
        return 0;
    }

