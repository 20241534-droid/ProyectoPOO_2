    private void limpiarCampos() {
        txtNombre.setText("");
        txtMonto.setText("");
        txtInicioVigencia.setText("");
        txtFinVigencia.setText("");
        cbTipo.setSelectedIndex(0);
    }
    
    // Método para convertir String a Date
    private Date parseFecha(String fecha) {
        try {
            return sdf.parse(fecha);
        } catch(Exception e) {
            return new Date(); // Si hay error, devuelve fecha actual
        }
    }
    
    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {                                     
        int fila = jTable1.getSelectedRow();
        if(fila != -1) {
            txtNombre.setText(modelo.getValueAt(fila, 0).toString());
            cbTipo.setSelectedItem(modelo.getValueAt(fila, 1).toString());
            txtMonto.setText(modelo.getValueAt(fila, 2).toString());
            txtInicioVigencia.setText(modelo.getValueAt(fila, 3).toString());
            txtFinVigencia.setText(modelo.getValueAt(fila, 4).toString());
        }
    }
    
