    private void btRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btRegistrarActionPerformed
        // TODO add your handling code here:
        String nombre = txtNombre.getText();
        String tipo = cbTipo.getSelectedItem().toString();
        double monto = Double.parseDouble(txtMonto.getText());
        Date inicio = parseFecha(txtInicioVigencia.getText());
        Date fin = parseFecha(txtFinVigencia.getText());

        modelo.addRow(new Object[]{nombre, tipo, monto, sdf.format(inicio), sdf.format(fin)});
        limpiarCampos();                                          

    }//GEN-LAST:event_btRegistrarActionPerformed

    private void btEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btEliminarActionPerformed
        // TODO add your handling code here:
        int fila = jTable1.getSelectedRow();
        if(fila != -1) {
            modelo.removeRow(fila);
        }
    }//GEN-LAST:event_btEliminarActionPerformed

    private void btModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btModificarActionPerformed
        // TODO add your handling code here:
        
        int fila = jTable1.getSelectedRow();
        if(fila != -1) {
            modelo.setValueAt(txtNombre.getText(), fila, 0);
            modelo.setValueAt(cbTipo.getSelectedItem().toString(), fila, 1);
            modelo.setValueAt(Double.parseDouble(txtMonto.getText()), fila, 2);
            modelo.setValueAt(txtInicioVigencia.getText(), fila, 3);
            modelo.setValueAt(txtFinVigencia.getText(), fila, 4);
        }
        
    }//GEN-LAST:event_btModificarActionPerformed

