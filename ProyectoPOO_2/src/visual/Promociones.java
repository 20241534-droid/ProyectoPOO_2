    // Devuelve un array de String con todas las promociones (solo nombre)
    public String[] getPromociones() {
        int filas = modelo.getRowCount();
        String[] promos = new String[filas];
        for(int i = 0; i < filas; i++) {
            promos[i] = modelo.getValueAt(i, 0).toString();
        }
        return promos;
    }

    // Devuelve el monto de una promoción según su nombre
    public double getMonto(String nombrePromocion) {
        int filas = modelo.getRowCount();
        for(int i = 0; i < filas; i++) {
            String nombre = modelo.getValueAt(i, 0).toString();
            if(nombre.equals(nombrePromocion)) {
                return Double.parseDouble(modelo.getValueAt(i, 2).toString());
            }
        }
        return 0;
    }

